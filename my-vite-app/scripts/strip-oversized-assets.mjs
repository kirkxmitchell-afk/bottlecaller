#!/usr/bin/env node
/**
 * Cloudflare Workers rejects any static asset over 25 MiB.
 * Strip oversized files from dist after Vite copies public/ → dist/.
 */
import { readdirSync, statSync, rmSync, existsSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const MAX_BYTES = 25 * 1024 * 1024;
const root = fileURLToPath(new URL("..", import.meta.url));
const dist = join(root, "dist");

if (!existsSync(dist)) {
  console.log("[strip-oversized-assets] no dist/ directory; skipping");
  process.exit(0);
}

const removed = [];

function walk(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      walk(full);
      continue;
    }
    const size = statSync(full).size;
    if (size > MAX_BYTES) {
      rmSync(full, { force: true });
      removed.push({ path: relative(dist, full), size });
    }
  }
}

walk(dist);

// Godot binaries cannot ship on Workers; drop the whole export folder from dist.
const godotDir = join(dist, "godot-shift");
if (existsSync(godotDir)) {
  rmSync(godotDir, { recursive: true, force: true });
  removed.push({ path: "godot-shift/", size: 0 });
}

// Ensure Wrangler also ignores Godot binaries even if copied later.
writeFileSync(
  join(dist, ".assetsignore"),
  [
    "# Generated by scripts/strip-oversized-assets.mjs",
    "godot-shift/",
    "**/*.pck",
    "**/*.wasm",
    "",
  ].join("\n"),
  "utf8",
);

if (removed.length) {
  console.log("[strip-oversized-assets] removed files over 25 MiB:");
  for (const item of removed) {
    const mb = (item.size / (1024 * 1024)).toFixed(1);
    console.log(`  - ${item.path} (${mb} MiB)`);
  }
} else {
  console.log("[strip-oversized-assets] no oversized files found");
}
